// Bundles every recording the app uses (your own + the Indian voice) into the app, so the
// APK plays them anywhere — offline, with no server. Run after recording or filling voices:
//   npm run voicepack        then rebuild the app / APK.
// Writes:
//   app/assets/voice/*.mp3            the audio, re-encoded to 48 kbps mono (clear speech, small)
//   app/src/lib/voicepack.ts          a map from each recording's server path to its bundled file
//   app/assets/library-snapshot.json  the library itself, so a fresh install has everything
import { execFile } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';

const run = promisify(execFile);
const ROOT = path.dirname(fileURLToPath(import.meta.url));
const DB_FILE = path.join(process.env.DATA_DIR || path.join(ROOT, 'data'), 'db.json');
const UPLOAD_DIR = process.env.UPLOAD_DIR || path.join(ROOT, 'uploads');
const APP = path.join(ROOT, '..', 'app');
const OUT_AUDIO = path.join(APP, 'assets', 'voice');
const OUT_MAP = path.join(APP, 'src', 'lib', 'voicepack.ts');
const OUT_LIBRARY = path.join(APP, 'assets', 'library-snapshot.json');

const db = JSON.parse(fs.readFileSync(DB_FILE, 'utf8'));
const items = db.items
  .filter((i) => i.published)
  .sort((a, b) => a.order - b.order || (a.title.en || '').localeCompare(b.title.en || ''));

// Every audio path the app can play.
const used = new Set();
const add = (u) => typeof u === 'string' && u.startsWith('/uploads/') && used.add(u);
for (const it of items) {
  add(it.fullAudioUrl);
  Object.values(it.titleAudio || {}).forEach(add);
  Object.values(it.meaningAudio || {}).forEach(add);
  for (const l of it.lines) {
    add(l.audioUrl);
    Object.values(l.meaningAudio || {}).forEach(add);
  }
}
const prompts = {};
for (const [key, entry] of Object.entries(db.prompts || {})) {
  const langs = Object.fromEntries(Object.entries(entry).filter(([k, v]) => /^[a-z]{2,3}$/.test(k) && v));
  Object.values(langs).forEach(add);
  prompts[key] = langs;
}

fs.mkdirSync(OUT_AUDIO, { recursive: true });
const bundled = new Map(); // server path -> bundled file name
let encoded = 0;
let reused = 0;
let missing = 0;
for (const u of [...used].sort()) {
  const src = path.join(UPLOAD_DIR, path.basename(u));
  if (!fs.existsSync(src)) {
    missing++;
    continue;
  }
  const name = path.basename(u).replace(/\.[^.]+$/, '') + '.mp3';
  const dest = path.join(OUT_AUDIO, name);
  if (fs.existsSync(dest) && fs.statSync(dest).mtimeMs >= fs.statSync(src).mtimeMs) {
    reused++;
  } else {
    await run('ffmpeg', ['-y', '-loglevel', 'error', '-i', src, '-vn', '-ac', '1', '-ar', '24000', '-b:a', '48k', dest]);
    encoded++;
  }
  bundled.set(u, name);
}

// Remove bundled files that are no longer used.
const keep = new Set(bundled.values());
let removed = 0;
for (const f of fs.readdirSync(OUT_AUDIO)) {
  if (!keep.has(f)) {
    fs.rmSync(path.join(OUT_AUDIO, f));
    removed++;
  }
}

const entries = [...bundled].map(([u, name]) => `  ${JSON.stringify(u)}: require('../../assets/voice/${name}'),`).join('\n');
fs.writeFileSync(
  OUT_MAP,
  `// Generated by \`npm run voicepack\` in cms/ — do not edit by hand.
// Recordings bundled into the app (server path -> audio asset), so they play offline anywhere.
export const VOICE_PACK: Record<string, number> = {
${entries}
};
`,
);
fs.writeFileSync(OUT_LIBRARY, JSON.stringify({ items, prompts }));

const bytes = [...keep].reduce((n, f) => n + fs.statSync(path.join(OUT_AUDIO, f)).size, 0);
console.log(
  `Voice pack: ${bundled.size} recordings (${(bytes / 1024 / 1024).toFixed(1)} MB) · ${encoded} encoded, ${reused} unchanged, ${removed} removed` +
    (missing ? `, ${missing} missing on disk` : '') +
    `\nLibrary: ${items.length} items bundled. Now rebuild the app / APK.`,
);
